MODEL = "openai/gpt-oss-20b"


# ==========================================
# 2. BAKERY MENU
# ==========================================

MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}


# ==========================================
# 3. SYSTEM PROMPT
# ==========================================

SYSTEM = f"""
ROLE:
You are a friendly AI assistant for Sweet Crumbs Home Bakery.

FACTS:
Menu with prices in rupees:
{json.dumps(MENU)}

- Orders require 24 hours' notice.
- All cakes have eggless versions.

RULES:
1. Be friendly and helpful.
2. Remember the customer's name and order during the conversation.
3. Never invent menu items or prices.
4. Use the price calculation tool when customers ask for
   the total price.
5. Never promise a delivery time.
6. If information is unavailable, say:
   "I'll check with the owner."
7. Respond in English or Telugu according to the customer.
8. Keep responses under 50 words.
"""


# ==========================================
# 4. LOGGING DECORATOR
# ==========================================

def log_call(func):

    @functools.wraps(func)
    def wrapper(*args, **kwargs):

        result = func(*args, **kwargs)

        print(f"[LOG] {func.__name__} -> {result}")

        return result

    return wrapper


# ==========================================
# 5. PRICE CALCULATION FUNCTION
# ==========================================

@log_call
def get_price(item: str, qty: int = 1) -> dict:

    item = item.lower().strip()

    if item not in MENU:
        return {
            "success": False,
            "message": "Item not available in menu."
        }

    if not isinstance(qty, int) or isinstance(qty, bool) or qty < 1:
        return {
            "success": False,
            "message": "Quantity must be a positive integer."
        }

    total = MENU[item] * qty

    return {
        "success": True,
        "item": item,
        "quantity": qty,
        "unit_price": MENU[item],
        "total_price": total
    }


# ==========================================
# 6. FUNCTION CALLING / TOOL DEFINITION
# ==========================================

tools = [
    {
        "type": "function",
        "function": {
            "name": "get_price",
            "description": "Calculate the total price of bakery items.",
            "parameters": {
                "type": "object",
                "properties": {
                    "item": {
                        "type": "string",
                        "enum": list(MENU.keys())
                    },
                    "qty": {
                        "type": "integer",
                        "description": "Number of items"
                    }
                },
                "required": ["item", "qty"],
                "additionalProperties": False
            }
        }
    }
]


# ==========================================
# 7. CONVERSATION HISTORY
# ==========================================

history = [
    {
        "role": "system",
        "content": SYSTEM
    }
]

MAX_TURNS = 8


def trim_history():

    # Keep the latest 8 complete user conversations.
    messages = history[1:]

    user_positions = [
        i for i, msg in enumerate(messages)
        if msg["role"] == "user"
    ]

    if len(user_positions) > MAX_TURNS:

        start = user_positions[-MAX_TURNS]

        history[:] = [history[0]] + messages[start:]


# ==========================================
# 8. CHAT FUNCTION
# ==========================================

def chat(user_text: str) -> str:

    history.append({
        "role": "user",
        "content": user_text
    })

    try:

        messages = history.copy()

        response = client.chat.completions.create(
            model=MODEL,
            messages=messages,
            tools=tools,
            tool_choice="auto",
            temperature=0.3
        )

        message = response.choices[0].message

        # Handle function calls
        tool_rounds = 0
        MAX_TOOL_ROUNDS = 5

        while message.tool_calls:

            tool_rounds += 1

            if tool_rounds > MAX_TOOL_ROUNDS:
                reply = "Sorry, I couldn't complete that request."
                history.append({
                    "role": "assistant",
                    "content": reply
                })
                trim_history()
                return reply

            # Save assistant tool-call message
            history.append(
                message.model_dump(exclude_none=True)
            )

            # Execute requested functions
            for tool_call in message.tool_calls:

                function_name = tool_call.function.name

                arguments = json.loads(
                    tool_call.function.arguments
                )

                if function_name == "get_price":

                    result = get_price(**arguments)

                else:

                    result = {
                        "success": False,
                        "message": "Unknown function."
                    }

                # Send function result back to LLM
                history.append({
                    "role": "tool",
                    "tool_call_id": tool_call.id,
                    "content": json.dumps(result)
                })

            # Ask the LLM to generate the final answer
            response = client.chat.completions.create(
                model=MODEL,
                messages=history.copy(),
                tools=tools,
                tool_choice="auto",
                temperature=0.3
            )

            message = response.choices[0].message

        reply = message.content or "I'll check with the owner."

    except AuthenticationError:

        reply = "Invalid API key. Please check your Groq API key."

    except RateLimitError:

        reply = "We're a little busy. Please try again in a minute."

    except APIConnectionError:

        reply = "I can't reach the server right now. Please try again shortly."

    except (ValueError, TypeError, KeyError, json.JSONDecodeError):

        reply = "Sorry, something went wrong. Please try again."

    history.append({
        "role": "assistant",
        "content": reply
    })

    trim_history()

    return reply


